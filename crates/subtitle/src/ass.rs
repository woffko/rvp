//! Advanced `SubStation` Alpha (ASS) and `SubStation` Alpha v4 (SSA): the
//! events of the `[Events]` section in the order of its `Format:` line;
//! every other section is kept as read (see the crate's documentation).

use crate::text::tags_to_ass;
use crate::time::{format_ass, parse_clock};
use crate::{AssEvent, Cue, Document, Format};

/// The events' fields FFmpeg and Aegisub write.
const DEFAULT_FORMAT: [&str; 10] = [
    "Layer", "Start", "End", "Style", "Name", "MarginL", "MarginR", "MarginV", "Effect", "Text",
];

/// The script info and style RVP writes for subtitles from SRT or `WebVTT`:
/// FFmpeg's default ASS header (Arial 16 on a 384x288 script, white with a
/// black outline), which mpv's own style options then override.
const DEFAULT_HEADER: &str = "[Script Info]
; Script generated by RVP
ScriptType: v4.00+
PlayResX: 384
PlayResY: 288
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,Arial,16,&Hffffff,&Hffffff,&H0,&H0,0,0,0,0,100,100,0,0,1,1,0,2,10,10,10,0

";

/// Text normalized to LF (see [`Document::parse_str`]).
pub(crate) fn parse(text: &str) -> Document {
    let mut document = Document::new(Format::Ass);
    let lines: Vec<&str> = text.lines().collect();
    let is_section = |line: &str| {
        let line = line.trim();
        line.starts_with('[') && line.ends_with(']')
    };
    let events_at = lines
        .iter()
        .position(|line| line.trim().eq_ignore_ascii_case("[events]"));
    let Some(events_at) = events_at else {
        document.header = ended(&lines);
        return document;
    };
    let trailer_at = lines[events_at + 1..]
        .iter()
        .position(|line| is_section(line))
        .map_or(lines.len(), |n| events_at + 1 + n);
    document.header = ended(&lines[..events_at]);
    document.trailer = ended(&lines[trailer_at..]);
    let mut format: Vec<String> = DEFAULT_FORMAT.iter().map(|f| (*f).to_owned()).collect();
    for line in &lines[events_at + 1..trailer_at] {
        let Some((kind, value)) = line.split_once(':') else {
            continue;
        };
        match kind.trim() {
            "Format" => {
                format = value
                    .split(',')
                    .map(|field| field.trim().to_owned())
                    .collect();
            }
            kind @ ("Dialogue" | "Comment") => {
                if let Some(cue) = event(&format, kind == "Comment", value) {
                    document.cues.push(cue);
                }
            }
            _ => {}
        }
    }
    document.ass_format = format;
    document
}

/// Lines each ended by `'\n'`.
fn ended(lines: &[&str]) -> String {
    let mut out = String::new();
    for line in lines {
        out.push_str(line);
        out.push('\n');
    }
    out
}

/// One event of the `[Events]` section.
fn event(format: &[String], comment: bool, value: &str) -> Option<Cue> {
    let value = value.strip_prefix(' ').unwrap_or(value);
    let fields: Vec<String> = value.splitn(format.len(), ',').map(str::to_owned).collect();
    if fields.len() != format.len() {
        return None;
    }
    let field = |name: &str| {
        format
            .iter()
            .position(|f| f.eq_ignore_ascii_case(name))
            .map(|at| fields[at].as_str())
    };
    let start_ms = parse_clock(field("Start")?)?;
    let end_ms = parse_clock(field("End")?)?;
    let text = field("Text").unwrap_or_default().replace("\\N", "\n");
    let mut cue = Cue::new(start_ms, end_ms, text);
    cue.style = field("Style").map(|style| style.trim().to_owned());
    cue.ass = Some(AssEvent { comment, fields });
    Some(cue)
}

/// The document as ASS, CRLF line ends.
pub(crate) fn write(document: &Document) -> String {
    let own = document.format == Format::Ass && !document.ass_format.is_empty();
    let header = if own {
        document.header.as_str()
    } else {
        DEFAULT_HEADER
    };
    let format: Vec<&str> = if own {
        document.ass_format.iter().map(String::as_str).collect()
    } else {
        DEFAULT_FORMAT.to_vec()
    };
    let mut out = String::new();
    for line in header.lines() {
        out.push_str(line);
        out.push_str("\r\n");
    }
    out.push_str("[Events]\r\nFormat: ");
    out.push_str(&format.join(", "));
    out.push_str("\r\n");
    for cue in &document.cues {
        if !own && cue.is_comment() {
            continue;
        }
        let text = if document.format == Format::Ass {
            cue.text.clone()
        } else {
            tags_to_ass(&cue.text)
        };
        let comment = cue.is_comment();
        let read = cue
            .ass
            .as_ref()
            .filter(|event| own && event.fields.len() == format.len());
        let fields: Vec<String> = format
            .iter()
            .enumerate()
            .map(|(at, name)| match name.to_ascii_lowercase().as_str() {
                "start" => format_ass(cue.start_ms),
                "end" => format_ass(cue.end_ms),
                "style" => cue.style.clone().unwrap_or_else(|| "Default".to_owned()),
                "text" => text.replace('\n', "\\N"),
                _ => read.map_or_else(|| default_field(name), |event| event.fields[at].clone()),
            })
            .collect();
        out.push_str(if comment { "Comment: " } else { "Dialogue: " });
        out.push_str(&fields.join(","));
        out.push_str("\r\n");
    }
    if !document.trailer.is_empty() {
        if !own || !document.trailer.starts_with('\n') {
            out.push_str("\r\n");
        }
        for line in document.trailer.lines() {
            out.push_str(line);
            out.push_str("\r\n");
        }
    }
    out
}

/// A field of an event RVP made: SSA's `Marked=0`, zero margins and layer,
/// empty names and effects.
fn default_field(name: &str) -> String {
    match name.to_ascii_lowercase().as_str() {
        "marked" => "Marked=0".to_owned(),
        "layer" | "marginl" | "marginr" | "marginv" => "0".to_owned(),
        _ => String::new(),
    }
}
